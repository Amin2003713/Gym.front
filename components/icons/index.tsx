/* HamOwj icon entry point.
   Every frontend icon import goes through this module so the HamOwj visual language
   (24px grid, 1.75 stroke, RTL mirroring) is used instead of raw lucide defaults.
   The pack has no media-control glyphs, so those few keep the same stroke family. */
import { forwardRef } from 'react'
import type { LucideIcon, LucideProps } from 'lucide-react'
import { HW_ICONS, HW_MIRROR_IN_RTL } from './hamowj-icons'

function packIcon(name: keyof typeof HW_ICONS): LucideIcon {
  const Glyph = HW_ICONS[name]

  const Wrapped = forwardRef<SVGSVGElement, LucideProps>((props, ref) => {
    const mirror = HW_MIRROR_IN_RTL.has(name) ? 'rtl:-scale-x-100' : ''
    const className = [props.className, mirror].filter(Boolean).join(' ')

    return (
      <Glyph
        ref={ref}
        {...props}
        strokeWidth={props.strokeWidth ?? 1.75}
        className={className}
      />
    )
  })

  Wrapped.displayName = `HamOwjIcon(${name})`
  return Wrapped as LucideIcon
}

