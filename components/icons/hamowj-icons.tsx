/** Icons whose meaning is directional and must mirror in RTL. */
export const HW_MIRROR_IN_RTL: ReadonlySet<HwIconName> = new Set([
  "history",
  "sidebar-toggle",
  "sign-out",
  "undo",
  "external-link",
  "play",
  "chevron-start",
  "chevron-end",
  "arrow-back",
  "arrow-forward"
] as HwIconName[])

export type HwIconName = keyof typeof HW_ICONS

export interface HwIconProps extends Omit<React.SVGProps<SVGSVGElement>, "ref"> {
  name: HwIconName
  size?: 16 | 20 | 24 | 32
  /** Accessible name. Omit for decorative icons (they become aria-hidden). */
  label?: string
}

export function HwIcon({ name, size = 20, label, className = "", ...rest }: HwIconProps) {
  const Cmp = HW_ICONS[name]
  const mirror = HW_MIRROR_IN_RTL.has(name) ? " rtl:-scale-x-100" : ""
  return (
    <Cmp
      width={size}
      height={size}
      strokeWidth={1.75}
      aria-hidden={label ? undefined : true}
      aria-label={label}
      role={label ? "img" : undefined}
      className={className + mirror}
      {...rest}
    />
  )
}
